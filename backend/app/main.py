@app.post("/predict/batch", response_model=BatchPredictResponse)
def batch_predict(file: UploadFile = File(..., description="CSV file with 21 feature columns")):
    """Batch prediction endpoint for CSV upload. Max 5,000 rows. Processes in memory only."""
    try:
        # Read CSV file into memory
        contents = file.file.read()
        df = pd.read_csv(io.BytesIO(contents))
        
        # Call batch prediction method
        result = manager.batch_predict(df)
        
        return result
    except ValueError as e:
        # Validation errors (too many rows, missing columns, etc.)
        if "Maximum" in str(e):
            raise HTTPException(status_code=413, detail=str(e))
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/extract-report", response_model=ReportExtractionResponse)
async def extract_medical_report(file: UploadFile = File(..., description="Medical report in PDF, JPG, PNG, or JPEG format")):
    """
    Extracts text from medical reports via PDF parsing or OCR.
    Extracts available BRFSS survey fields (Auto-filled, Needs Confirmation, or Not Found).
    Never guesses missing values or maps unrelated lab indicators (like HbA1c) to survey features.
    """
    filename = file.filename or "uploaded_report"
    ext = os.path.splitext(filename)[1].lower()
    allowed_exts = {".pdf", ".jpg", ".jpeg", ".png"}
    if ext not in allowed_exts:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file format '{ext}'. Allowed formats are PDF, JPG, PNG, JPEG."
        )

    try:
        contents = await file.read()
        if not contents or len(contents) == 0:
            raise HTTPException(status_code=400, detail="Uploaded file is empty (0 bytes).")
        
        if len(contents) > 15 * 1024 * 1024:
            raise HTTPException(status_code=413, detail="File too large. Maximum size is 15 MB.")

        result = parse_medical_report(contents, filename, file.content_type)
        return result
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Medical report processing failed: {str(e)}")

@app.get("/sample-report/{report_name}")
def get_sample_report(report_name: str):
    valid_samples = {
        "comprehensive": ("comprehensive_patient_report.pdf", "application/pdf"),
        "minimal": ("minimal_incomplete_report.pdf", "application/pdf"),
        "scanned": ("scanned_clinic_note.png", "image/png"),
    }
    if report_name not in valid_samples:
        raise HTTPException(status_code=404, detail=f"Sample report '{report_name}' not found. Use: comprehensive, minimal, scanned")
    
    filename, mime = valid_samples[report_name]
    # Check project root, then backend directory
    candidate_paths = [
        os.path.join(os.path.dirname(BASE_DIR), "sample_reports", filename),
        os.path.join(BASE_DIR, "sample_reports", filename),
        os.path.join("sample_reports", filename)
    ]
    filepath = None
    for p in candidate_paths:
        if os.path.exists(p):
            filepath = p
            break

    if not filepath or not os.path.exists(filepath):
        raise HTTPException(status_code=404, detail=f"Sample report file '{filename}' not found on server.")
    
    from fastapi.responses import FileResponse
    return FileResponse(filepath, media_type=mime, filename=filename)

@app.get("/health")
async def health_check():
    """
    Health check endpoint with Gemini status and vector DB info.
    """
    gemini_key = os.getenv('GEMINI_API_KEY') or os.getenv('GOOGLE_API_KEY')
    gemini_configured = bool(gemini_key)
    gemini_reachable = False
    if gemini_configured:
        try:
            from backend.app.gemini_utils import probe_gemini
            probe = probe_gemini(gemini_key, os.getenv('GEMINI_MODEL'))
            gemini_reachable = bool(probe.get('succeeded'))
        except Exception as e:
            from backend.app.gemini_utils import redact_api_key
            print(f"[Health] Gemini reachability check failed: {redact_api_key(str(e), gemini_key)}")
            gemini_reachable = False

    try:
        vector_db_chunks = int(chat_service.collection.count()) if chat_service.collection is not None else 0
    except Exception as e:
        print(f"[Health] Vector database count failed: {e}")
        vector_db_chunks = 0
    
    return {
        "gemini_configured": gemini_configured,
        "gemini_reachable": gemini_reachable,
        "vector_db_chunks": vector_db_chunks,
        "embedding_model": "BAAI/bge-small-en-v1.5",
        "version": "2.4.0"
    }

@app.post("/chat", response_model=ChatResponse, response_model_exclude_none=True)
async def chat(request: ChatRequest):
    """
    RAG chatbot endpoint for answering diabetes-related health questions.
    Retrieves relevant context from knowledge base, checks safety, and generates responses.
    """
    debug_mode = os.getenv('DEBUG_CHAT') == '1'
    
    try:
        # Convert conversation history to dict format
        history = None
        if request.conversation_history:
            history = [{"role": msg.role, "content": msg.content} for msg in request.conversation_history]
        
        # Call chat service with debug flag
        result = chat_service.chat(
            query=request.query,
            conversation_history=history,
            k=request.k,
            source_type=request.source_type,
            min_score=request.min_score,
            debug=debug_mode
        )
        
        return ChatResponse(**result)
    except Exception as e:
        message = str(e)
        secret = os.getenv('GEMINI_API_KEY') or os.getenv('GOOGLE_API_KEY')
        if secret:
            message = message.replace(secret, '[REDACTED]')
        raise HTTPException(status_code=500, detail=f"Chat processing failed: {message}")


@app.post("/chat/ablation")
async def chat_context_ablation(request: ChatRequest):
    """Debug-only grounding check: ask the configured generator with an empty context."""
    if os.getenv('DEBUG_CHAT') != '1':
        raise HTTPException(status_code=404, detail="Not found")
    if not chat_service.gemini_key:
        raise HTTPException(status_code=503, detail="Gemini is not configured")
    prompt = f"CONTEXT:\n\nUSER QUESTION: {request.query.strip()}\n\nAnswer:"
    try:
        answer = chat_service.call_configured_llm(prompt, 'gemini', chat_service.gemini_key)
        return {
            'answer': answer or '',
            'provider': 'gemini',
            'model': chat_service.last_llm_metadata.get('model'),
            'tokens': chat_service.last_llm_metadata.get('tokens'),
            'empty_context': True,
        }
    except Exception as e:
        message = str(e).replace(chat_service.gemini_key, '[REDACTED]') if chat_service.gemini_key else str(e)
        raise HTTPException(status_code=502, detail=f"Gemini ablation call failed: {message}")

