@app.post("/predict", response_model=PredictResponse)
def predict(payload: FeatureInput):
    try:
        data = payload.dict()
        res = manager.predict(data)
        return res
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/explain", response_model=ExplainResponse)
def explain(payload: FeatureInput):
    try:
        data = payload.dict()
        res = manager.explain(data)
        return res
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.get("/explain/{prediction_id}", response_model=ExplainResponse)
def explain_by_id(prediction_id: str = Path(..., description="The prediction ID generated by /predict")):
    cached = manager.prediction_cache.get(prediction_id)
    if not cached:
        raise HTTPException(status_code=404, detail=f"Prediction ID '{prediction_id}' not found in cache.")
    return manager.explain(cached["inputs"], prediction_id=prediction_id)

